"""Generate src/sgostd/crypto/x509/roots/bundle.sgo from Go's golang.org/x/crypto/x509roots/fallback
bundle (the Mozilla root list) at the pinned VERSION (D201).

    gen-roots.py           rewrite the bundle file
    gen-roots.py --check   fail if the bundle file differs from what the pinned version generates

To take a new Mozilla list: change VERSION, run this script, and record the change in the spec
changelog; the pinned version and the bundle digest are in the generated file.
"""
import calendar
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import time

VERSION = "v0.0.0-20261105095718-a1058eb15227"
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "src", "sgostd", "crypto", "x509", "roots", "bundle.sgo")


def go():
    pinned = json.load(open(os.path.join(ROOT, "sgo", "UPSTREAM.lock.json")))["bootstrap"]["pinned_version"]
    plat = "%s-%s" % ({"darwin": "darwin", "linux": "linux"}[sys.platform if sys.platform != "linux2" else "linux"],
                      {"arm64": "arm64", "aarch64": "arm64", "x86_64": "amd64"}[os.uname().machine])
    cache = os.environ.get("SGO_CACHE", os.path.expanduser("~/.cache/sgolang"))
    return os.path.join(cache, "bootstrap", f"{pinned}-{plat}", "go", "bin", "go")


def bundle_dir():
    with tempfile.TemporaryDirectory() as d:
        open(os.path.join(d, "go.mod"), "w").write("module rootsfetch\n\ngo 1.26\n")
        r = subprocess.run([go(), "mod", "download", "-json", "golang.org/x/crypto/x509roots/fallback@" + VERSION],
                           cwd=d, capture_output=True, text=True, timeout=900, env=dict(os.environ, GOFLAGS="-mod=mod"))
        if r.returncode:
            sys.exit("gen-roots: go mod download failed:\n" + r.stderr)
        return json.loads(r.stdout)["Dir"]


def generate():
    d = os.path.join(bundle_dir(), "bundle")
    der = open(os.path.join(d, "bundle.der"), "rb").read()
    src = open(os.path.join(d, "bundle.go")).read()
    entries = []
    for m in re.finditer(r"\{\s*cn:\s*\"((?:[^\"\\]|\\.)*)\",\s*sha256Hash:\s*\"([0-9a-f]{64})\",\s*"
                         r"certStartOff:\s*(\d+),\s*certLength:\s*(\d+),\s*(?:distrustAfter:\s*\"([^\"]+)\",\s*)?\}", src):
        cn, h, off, n, after = m.group(1), m.group(2), int(m.group(3)), int(m.group(4)), m.group(5)
        cert = der[off:off + n]
        assert hashlib.sha256(cert).hexdigest() == h, cn
        t = 0
        if after:
            t = calendar.timegm(time.strptime(after, "%Y-%m-%dT%H:%M:%SZ"))
        entries.append((cn.replace("\\\\", "\\"), cert.hex(), t))
    assert len(entries) == src.count("cn:"), "unparsed entries"
    digest = hashlib.sha256(der).hexdigest()
    rows = []
    for cn, hx, t in entries:
        rows.append("\t// %s\n\trootEntry{der: \"%s\", distrustAfter: %d}," % (cn, hx, t))
    return '''// Copyright 2026 The S-Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.

// Code generated by sgo/scripts/gen-roots.py; DO NOT EDIT.

package roots

import "sgo"

// BundleVersion is the golang.org/x/crypto/x509roots/fallback version the roots come from.
const BundleVersion = "%s"

// BundleSHA256 is the SHA-256 of that version's bundle.der, the concatenated root certificates.
const BundleSHA256 = "%s"

// Count is the number of roots in the bundle.
const Count = %d

var bundle = sgo.Freeze([]rootEntry{
%s
})
''' % (VERSION, digest, len(entries), "\n".join(rows))


def main():
    out = generate()
    if "--check" in sys.argv[1:]:
        if not os.path.exists(OUT) or open(OUT).read() != out:
            sys.exit("gen-roots: %s is stale; run sgo/scripts/gen-roots.py" % os.path.relpath(OUT, ROOT))
        print("gen-roots: ok: bundle matches %s" % VERSION)
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write(out)
    print("gen-roots: wrote %s (%d bytes) from %s" % (os.path.relpath(OUT, ROOT), len(out), VERSION))


if __name__ == "__main__":
    main()
