"""generated-twin-check.py — keep upstream's go/types generator consistent (W03).

go/types files marked 'Code generated by "go test -run=Generate -write=all"' are produced from
cmd/compile/internal/types2 sources by src/go/types/generate_test.go (its filemap). S-Go changes to
types2 must not touch those sources: every S-Go rule lives in non-generated files (sgo.go,
sgo_flow.go, or files without a go/types twin), so upstream's TestGenerate keeps passing. This
check fails if a types2 source in the filemap differs from the locked upstream commit, or if a
generated go/types file differs from upstream.

    generated-twin-check.py
"""
import json
import os
import re
import subprocess
import sys

ROOT = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
LOCK = json.load(open(os.path.join(ROOT, "sgo", "UPSTREAM.lock.json")))
UPSTREAM = LOCK["upstream"]["commit"]
T2 = "src/cmd/compile/internal/types2/"
GT = "src/go/types/"


def blob(rev, path):
    r = subprocess.run(["git", "-C", ROOT, "rev-parse", f"{rev}:{path}"], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else None


def main():
    if subprocess.run(["git", "-C", ROOT, "cat-file", "-e", UPSTREAM + "^{commit}"], capture_output=True).returncode:
        sys.exit(f"generated-twin-check: upstream commit {UPSTREAM} not in this clone (fetch full history)")
    gen = open(os.path.join(ROOT, GT, "generate_test.go")).read()
    names = sorted(set(re.findall(r'^\t"([A-Za-z0-9_]+\.go)":', gen, re.M)))
    if not names:
        sys.exit("generated-twin-check: no filemap entries found in go/types/generate_test.go")
    bad = []
    for n in names:
        for path in (T2 + n, GT + n):
            if os.path.exists(os.path.join(ROOT, path)) and blob("HEAD", path) != blob(UPSTREAM, path):
                bad.append(path)
            # the working tree must match HEAD too when run locally
            r = subprocess.run(["git", "-C", ROOT, "diff", "--quiet", "HEAD", "--", path])
            if r.returncode and path not in bad:
                bad.append(path + " (uncommitted)")
    if bad:
        print("generated-twin-check: these files feed or are produced by the go/types generator and must equal upstream:")
        for b in bad:
            print("  " + b)
        print("  move S-Go logic into types2 files without a go/types twin (e.g. sgo.go, sgo_flow.go)")
        return 1
    print(f"generated-twin-check: ok: {len(names)} generator inputs and outputs equal upstream {UPSTREAM[:12]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
