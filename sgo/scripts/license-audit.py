"""license-audit.py - licensing of the S-Go change against the upstream pin (D81, W12).

    license-audit.py [--fix]

Checks, for the diff from the upstream commit in sgo/UPSTREAM.lock.json to the work tree:
  - LICENSE and PATENTS are unchanged, and nothing under a vendor/ directory changed;
  - every added source file (.go .s .h .py .sh .sgo) outside testdata/ directories starts with
    the S-Go BSD header, or is generated (first line "Code generated ... DO NOT EDIT") by an
    S-Go script; --fix inserts the header where it is missing (after a #! line);
  - modified upstream files keep their upstream copyright header;
  - no added file carries another license or a foreign copyright notice (SPDX tag, Apache, MIT,
    GPL, "Copyright (c)" of someone other than the Go or S-Go authors).
Algorithms re-implemented from published descriptions (SplitMix64, PCG32 in the lab and model)
are not copied code and need no notice.
"""
import sgoargs
import json
import os
import re
import subprocess
import sys

ROOT = os.path.realpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
EXT = {".go": "//", ".s": "//", ".h": "//", ".sgo": "//", ".py": "#", ".sh": "#"}
HEADER = ["Copyright 2026 The S-Go Authors. All rights reserved.",
          "Use of this source code is governed by a BSD-style",
          "license that can be found in the LICENSE file."]
FOREIGN = re.compile(r"SPDX-License-Identifier|Apache License|MIT License|GNU (Lesser )?General Public|"
                     r"Copyright \(c\)(?! \d{4} The Go Authors)", re.I)


def git(*args):
    return subprocess.check_output(["git", "-C", ROOT] + list(args), text=True)


def pin():
    with open(os.path.join(ROOT, "sgo", "UPSTREAM.lock.json")) as f:
        lock = json.load(f)
    for k in ("upstream_commit", "commit"):
        v = lock.get(k) or lock.get("upstream", {}).get(k)
        if v:
            return v
    sys.exit("license-audit: no upstream commit in sgo/UPSTREAM.lock.json")


def needs_header(path):
    if any(part == "testdata" for part in path.split("/")):
        return False
    return os.path.splitext(path)[1] in EXT


def has_header(text):
    head = "\n".join(text.splitlines()[:6])
    return all(h in head for h in HEADER)


def generated(text):
    first = text.split("\n", 1)[0]
    return first.startswith("// Code generated by sgo/scripts/") and first.rstrip().endswith("DO NOT EDIT.")


def add_header(path, text):
    c = EXT[os.path.splitext(path)[1]]
    hdr = "".join(f"{c} {h}\n" for h in HEADER)
    if text.startswith("#!"):
        line, rest = text.split("\n", 1)
        return line + "\n" + hdr + rest
    return hdr + "\n" + text if c == "//" else hdr + text


def main():
    sgoargs.check(flags={"--fix": "bool"})  # strict command line (W12 R14)
    fix = "--fix" in sys.argv[1:]
    base = pin()
    errs, fixed = [], []
    changed = git("diff", "--name-status", base, "--").splitlines()
    for line in changed:
        st, path = line.split("\t", 1)[0], line.split("\t")[-1]
        if path in ("LICENSE", "PATENTS"):
            errs.append(f"{path} changed against the upstream pin")
        # Upstream's vendored third-party code must stay byte-identical. S-Go's own test fixtures
        # under sgo/testdata hold vendor/ trees of their own (required modules, SGO-IMP-003).
        if "/vendor/" in "/" + path and not path.startswith("sgo/testdata/"):
            errs.append(f"{path}: vendored code changed")
        full = os.path.join(ROOT, path)
        if st.startswith("D") or not os.path.isfile(full):
            continue
        try:
            text = open(full, encoding="utf-8").read()
        except UnicodeDecodeError:
            continue
        if st.startswith("A"):
            # This script names the markers it looks for; it is not itself a foreign notice.
            for m in ([] if path == "sgo/scripts/license-audit.py" else FOREIGN.finditer(text)):
                errs.append(f"{path}: foreign license or copyright marker {m.group(0)!r}")
            if needs_header(path) and not has_header(text) and not generated(text):
                if fix:
                    open(full, "w", encoding="utf-8").write(add_header(path, text))
                    fixed.append(path)
                else:
                    errs.append(f"{path}: missing S-Go header")
        elif st.startswith("M"):
            old = git("show", f"{base}:{path}")
            if "Copyright" in "\n".join(old.splitlines()[:5]) and "Copyright" not in "\n".join(text.splitlines()[:5]):
                errs.append(f"{path}: upstream copyright header removed")
    for p in fixed:
        print("license-audit: header added:", p)
    for e in errs:
        print("license-audit:", e, file=sys.stderr)
    if errs:
        print(f"license-audit: FAIL ({len(errs)} problems)", file=sys.stderr)
        return 1
    print(f"license-audit: ok ({len(changed)} changed paths against {base[:10]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
