"""make-release.py — the S-Go release archive (D61, W10).

    make-release.py [--out DIR]

Builds sgo-<spec version>-<os>-<arch>.tar.gz for the host from the current stage-0 toolchain:

    sgo-<v>-<os>-<arch>/
      bin/sgo                          -> ../pkg/tool/<os>_<arch>/sgo
      pkg/tool/<os>_<arch>/{sgo,compile,asm,link}
      src/...                          exactly the TCB files of sgo/TARGET_TCB.json (runtime, sgo, ...)
      sgo/spec/VERSION, sgo/SGO_SPEC_ADMISSION.json, sgo/TARGET_TCB.json, sgo/UPSTREAM.lock.json
      examples/                        the D66 examples
      LICENSE, PATENTS, INSTALL.md     (sgo/docs/INSTALL.md)

There is no go command, gofmt, or standard library source outside the TCB: the installation is
single-language. sgo finds its root from its own path, so installing is extracting the archive and
adding bin to PATH. The script refuses to write an archive holding any other executable.
"""
import hashlib
import json
import os
import platform
import re
import shutil
import stat
import subprocess
import sys
import tarfile
import tempfile

ROOT = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
GOOS = {"Darwin": "darwin", "Linux": "linux"}[platform.system()]
GOARCH = {"arm64": "arm64", "aarch64": "arm64", "x86_64": "amd64"}[platform.machine()]
TOOLS = ["sgo", "compile", "asm", "link"]
REGISTRY = ["sgo/spec/VERSION", "sgo/SGO_SPEC_ADMISSION.json", "sgo/TARGET_TCB.json", "sgo/UPSTREAM.lock.json"]


INCLUDE = re.compile(r'^#include\s+"([^"]+)"', re.M)


def asm_headers(manifest):
    """Headers the TCB's .s files include, resolved as the assembler does: next to the including
    file, then in runtime. go_asm.h is generated by each build and is not a file of the tree."""
    listed = {f["path"] for f in manifest["files"]}
    seen, todo = set(), [f["path"] for f in manifest["files"] if f["path"].endswith((".s", ".h"))]
    while todo:
        p = todo.pop()
        for h in INCLUDE.findall(open(os.path.join(ROOT, p)).read()):
            for c in (os.path.join(os.path.dirname(p), h), os.path.join("src", "runtime", h)):
                c = os.path.normpath(c)
                if os.path.exists(os.path.join(ROOT, c)):
                    if c not in seen:
                        seen.add(c)
                        todo.append(c)
                    break
    return sorted(seen - listed)


def main():
    out = os.getcwd()
    if sys.argv[1:2] == ["--out"]:
        out = os.path.abspath(sys.argv[2])
    version = open(os.path.join(ROOT, "sgo", "spec", "VERSION")).read().strip()
    name = f"sgo-{version}-{GOOS}-{GOARCH}"
    manifest = json.load(open(os.path.join(ROOT, "sgo", "TARGET_TCB.json")))
    tooldir = os.path.join("pkg", "tool", f"{GOOS}_{GOARCH}")
    with tempfile.TemporaryDirectory() as tmp:
        top = os.path.join(tmp, name)
        os.makedirs(os.path.join(top, tooldir))
        for t in TOOLS:
            shutil.copy2(os.path.join(ROOT, tooldir, t), os.path.join(top, tooldir, t))
        os.makedirs(os.path.join(top, "bin"))
        os.symlink(os.path.join("..", tooldir, "sgo"), os.path.join(top, "bin", "sgo"))
        for f in manifest["files"]:
            src = os.path.join(ROOT, f["path"])
            if hashlib.sha256(open(src, "rb").read()).hexdigest() != f["sha256"]:
                sys.exit(f"make-release: {f['path']} differs from TARGET_TCB.json; regenerate and rebuild first")
            dst = os.path.join(top, f["path"])
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(src, dst)
        # Assembly headers the TCB includes from outside its packages (cgo/abi_*.h), pinned in
        # TARGET_TCB.json "headers" and verified by the driver before it assembles.
        if sorted(f["path"] for f in manifest.get("headers", [])) != asm_headers(manifest):
            sys.exit("make-release: TARGET_TCB.json headers are stale; run tcb-manifest.py --write")
        for f in manifest.get("headers", []):
            src = os.path.join(ROOT, f["path"])
            if hashlib.sha256(open(src, "rb").read()).hexdigest() != f["sha256"]:
                sys.exit(f"make-release: {f['path']} differs from TARGET_TCB.json")
            dst = os.path.join(top, f["path"])
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(src, dst)
        for f in REGISTRY + ["LICENSE", "PATENTS"]:
            dst = os.path.join(top, f)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(os.path.join(ROOT, f), dst)
        ex = subprocess.check_output(["git", "ls-files", "sgo/examples"], cwd=ROOT, text=True).split()
        for f in ex:
            dst = os.path.join(top, "examples", os.path.relpath(f, "sgo/examples"))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(os.path.join(ROOT, f), dst)
        shutil.copy2(os.path.join(ROOT, "sgo", "docs", "INSTALL.md"), os.path.join(top, "INSTALL.md"))
        # The replay example's trace names the build that recorded it (D46): record it with the
        # toolchain being released, so the shipped trace replays with the shipped build (D78).
        rp = os.path.join(top, "examples", "replay")
        with tempfile.TemporaryDirectory() as home:
            env = {"HOME": home, "PATH": "/usr/bin:/bin", "SGO_CACHE": os.path.join(home, "cache")}
            seed = json.loads(open(os.path.join(rp, "buggy.trace.jsonl")).readline())["seed"]
            fresh = os.path.join(home, "t.jsonl")
            subprocess.run([os.path.join(ROOT, tooldir, "sgo"), "lab", "sweep", "-seeds", f"{seed}..{seed}",
                            "-expect", "expected.txt", "-save", fresh, "./buggy"], cwd=rp, env=env,
                           capture_output=True, text=True)
            if not os.path.exists(fresh):
                sys.exit(f"make-release: seed {seed} no longer fails ./buggy; the replay example is stale")
            shutil.copy2(fresh, os.path.join(rp, "buggy.trace.jsonl"))
        # Single language: the only executables are the four tools.
        allowed = {os.path.join(tooldir, t) for t in TOOLS}
        for root, _, files in os.walk(top):
            for fn in files:
                p = os.path.join(root, fn)
                rel = os.path.relpath(p, top)
                if os.path.islink(p):
                    continue
                if os.stat(p).st_mode & stat.S_IXUSR and rel not in allowed and not rel.endswith((".sh", ".bash", ".py", ".pl")):
                    sys.exit(f"make-release: unexpected executable {rel}")
                if fn in ("go", "gofmt"):
                    sys.exit(f"make-release: {rel}: no go command or gofmt in a release (D61)")
        archive = os.path.join(out, name + ".tar.gz")
        with tarfile.open(archive, "w:gz") as tf:
            tf.add(top, arcname=name)
    print(f"make-release: wrote {archive} ({len(manifest['files'])} TCB files, {len(ex)} example files)")


if __name__ == "__main__":
    main()
