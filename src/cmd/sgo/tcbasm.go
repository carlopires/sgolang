package main

import (
	"crypto/sha256"
	"encoding/hex"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// The compiler verifies the Go files of a TCB package (SGO-TCB-002); the assembler has no such
// check, so the driver verifies every assembler input of the TCB before assembling it: each .s
// file and every header it includes, transitively, against the digests built into the driver
// (tcbtable.go, generated with the manifest). Headers are resolved as the assembler resolves
// them: next to the including file, then in runtime; go_asm.h is generated by the build.

var asmInclude = regexp.MustCompile(`(?m)^#include\s+"([^"]+)"`)

func tcbAsmDigests() map[string]string {
	m := map[string]string{}
	for _, line := range strings.Split(strings.TrimSpace(tcbAsmList), "\n") {
		if name, digest, ok := strings.Cut(line, " "); ok {
			m[name] = digest
		}
	}
	return m
}

// verifyAsm checks the assembler inputs of sfiles under goroot and returns them (headers
// included) as "path digest" lines for the TCB cache key.
func verifyAsm(goroot string, sfiles []string) ([]string, error) {
	want := tcbAsmDigests()
	src := filepath.Join(goroot, "src")
	seen := map[string]bool{}
	var lines []string
	var check func(file string) error
	check = func(file string) error {
		rel, err := filepath.Rel(src, file)
		if err != nil || strings.HasPrefix(rel, "..") {
			return &toolErr{file + ":1:1", "SGO_E_TCB_DIGEST", "assembler input " + file + " is outside the TCB (SGO-TCB-002)", 1}
		}
		rel = filepath.ToSlash(rel)
		if seen[rel] {
			return nil
		}
		seen[rel] = true
		data, err := os.ReadFile(file)
		if err != nil {
			return err
		}
		sum := sha256.Sum256(data)
		got := hex.EncodeToString(sum[:])
		switch d, ok := want[rel]; {
		case !ok:
			return &toolErr{file + ":1:1", "SGO_E_TCB_DIGEST", "assembler input " + rel + " is not in sgo/TARGET_TCB.json (SGO-TCB-002)", 1}
		case d != got:
			return &toolErr{file + ":1:1", "SGO_E_TCB_DIGEST", "assembler input " + rel + " differs from its digest in sgo/TARGET_TCB.json (SGO-TCB-002)", 1}
		}
		lines = append(lines, rel+" "+got)
		for _, m := range asmInclude.FindAllSubmatch(data, -1) {
			h := string(m[1])
			for _, c := range []string{filepath.Join(filepath.Dir(file), h), filepath.Join(src, "runtime", h)} {
				if _, err := os.Stat(c); err == nil {
					if err := check(filepath.Clean(c)); err != nil {
						return err
					}
					break
				}
			}
		}
		return nil
	}
	for _, f := range sfiles {
		if err := check(f); err != nil {
			return nil, err
		}
	}
	return lines, nil
}
