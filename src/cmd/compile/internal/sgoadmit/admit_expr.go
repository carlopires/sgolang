var legacyOctal = regexp.MustCompile(`^0[0-9_]+$`)

func (a *admitter) stmtList(list []syntax.Stmt) {
	for _, s := range list {
		a.stmt(s)
	}
}

func (a *admitter) stmt(s syntax.Stmt) {
	switch s := s.(type) {
	case nil:
	case *syntax.EmptyStmt:
		a.deny(s.Pos(), "empty statement", "SGO-CTL-001")
	case *syntax.LabeledStmt:
		a.stmt(s.Stmt)
	case *syntax.BlockStmt:
		a.stmtList(s.List)
	case *syntax.ExprStmt:
		a.expr(s.X)
	case *syntax.SendStmt:
		a.expr(s.Chan)
		a.expr(s.Value)
	case *syntax.DeclStmt:
		for _, d := range s.DeclList {
			switch d := d.(type) {
			case *syntax.ConstDecl:
				if d.Type != nil {
					a.typ(d.Type)
				}
				a.expr(d.Values)
			case *syntax.VarDecl:
				if d.Type != nil {
					a.typ(d.Type)
				}
				if x, ok := d.Values.(*syntax.AssertExpr); ok && len(d.NameList) == 2 {
					a.commaOK(x) // var v, ok = x.(T) (SGO-IFACE-004)
					break
				}
				a.expr(d.Values)
			case *syntax.TypeDecl:
				a.deny(a.tokenBefore(d.Pos(), "type"), "type declaration", "SGO-UTYPE-001")
			}
		}
	case *syntax.AssignStmt:
		a.expr(s.Lhs)
		if x, ok := s.Rhs.(*syntax.AssertExpr); ok {
			if l, ok := s.Lhs.(*syntax.ListExpr); ok && len(l.ElemList) == 2 {
				a.commaOK(x) // v, ok := x.(T) and v, ok = x.(T) (SGO-IFACE-004)
				return
			}
		}
		a.expr(s.Rhs)
	case *syntax.BranchStmt:
		switch s.Tok {
		case syntax.Goto:
			a.deny(s.Pos(), "goto", "SGO-CTL-001")
		case syntax.Fallthrough:
			a.deny(s.Pos(), "fallthrough", "SGO-CTL-002")
		}
	case *syntax.CallStmt:
		if s.Tok == syntax.Go {
			a.report(s.Pos(), "SGO_E_UNSTRUCTURED_SPAWN", "the go statement is not part of S-Go; spawn through a nursery handle (SGO-SPAWN-005)")
			return
		}
		a.expr(s.Call)
	case *syntax.ReturnStmt:
		a.expr(s.Results)
	case *syntax.IfStmt:
		a.stmt(s.Init)
		a.expr(s.Cond)
		a.stmt(s.Then)
		a.stmt(s.Else)
	case *syntax.ForStmt:
		if r, ok := s.Init.(*syntax.RangeClause); ok {
			// Range over channels, arrays, slices, and maps is admitted (SGO-CHAN-002, SGO-COMP-002,
			// SGO-COMP-005, SGO-COMP-006); types2 denies other operands. A range clause with = would
			// assign existing variables on every iteration, outside the capture rule's assignment
			// forms; it is denied (SGO-MEM-002, W13 review V4).
			if r.Lhs != nil && !r.Def {
				a.deny(r.Pos(), "range clause with = (declare the iteration variables with :=)", "SGO-MEM-002")
				return
			}
			a.expr(r.Lhs)
			a.expr(r.X)
			a.stmt(s.Body)
			return
		}
		a.stmt(s.Init)
		a.expr(s.Cond)
		a.stmt(s.Post)
		a.stmt(s.Body)
	case *syntax.SwitchStmt:
		if g, ok := s.Tag.(*syntax.TypeSwitchGuard); ok {
			// switch v := x.(type) (SGO-IFACE-004); types2 checks x and the case types.
			a.stmt(s.Init)
			a.expr(g.X)
			for _, c := range s.Body {
				for _, t := range syntax.UnpackListExpr(c.Cases) {
					if n, ok := t.(*syntax.Name); ok && n.Value == "nil" {
						continue
					}
					a.typ(t)
				}
				a.stmtList(c.Body)
			}
			return
		}
		a.stmt(s.Init)
		a.expr(s.Tag)
		for _, c := range s.Body {
			a.expr(c.Cases)
			a.stmtList(c.Body)
		}
	case *syntax.SelectStmt:
		for _, c := range s.Body {
			a.stmt(c.Comm)
			a.stmtList(c.Body)
		}
	case *syntax.NurseryStmt:
		if s.Name == nil {
			a.deny(s.Pos(), "anonymous nursery", "SGO-NUR-001")
			return
		}
		a.stmt(s.Body)
	}
}

func (a *admitter) funcType(t *syntax.FuncType) {
	for _, f := range t.ParamList {
		if _, ok := f.Type.(*syntax.DotsType); ok {
			a.deny(f.Type.Pos(), "variadic parameter", "SGO-TYPE-003")
			continue
		}
		a.typ(f.Type)
	}
	for _, f := range t.ResultList {
		a.typ(f.Type)
	}
}

// typ checks an expression in type position.
func (a *admitter) typ(e syntax.Expr) {
	switch e := e.(type) {
	case nil:
	case *syntax.Name:
		a.name(e)
	case *syntax.SelectorExpr:
		a.sgoSelector(e)
	case *syntax.Operation: // *T
		if e.Op == syntax.Mul && e.Y == nil {
			if sel, ok := e.X.(*syntax.SelectorExpr); ok && isSgo(sel) && sgoHandleTypes[sel.Sel.Value] {
				return
			}
			if ix, ok := e.X.(*syntax.IndexExpr); ok && a.sgoInstance(ix, "Channel", "SendPermit") {
				return
			}
			// *sgo.Task[T], *sgo.Group[T] (D161, D172; W22 review G1): handles a helper may take or a
			// declaration may name. T is any admitted type; types2 checks it, and the flow pass ties a
			// handle that delivers resources like any resource value.
			if ix, ok := e.X.(*syntax.IndexExpr); ok {
				if sel, ok := ix.X.(*syntax.SelectorExpr); ok && isSgo(sel) && (sel.Sel.Value == "Task" || sel.Sel.Value == "Group" || sel.Sel.Value == "Call" || sel.Sel.Value == "Request" || sel.Sel.Value == "Pool" || sel.Sel.Value == "Lease") {
					a.typ(ix.Index)
					return
				}
			}
			a.typ(e.X) // *T (SGO-COMP-007); types2 checks T (sgoFieldType)
			return
		}
		a.deny(e.Pos(), "type expression", "SGO-TYPE-001")
	case *syntax.FuncType:
		a.funcType(e)
	case *syntax.ParenExpr:
		a.typ(e.X)
	case *syntax.ArrayType:
		// [N]T with a value element type (SGO-COMP-002); types2 checks T (sgoValueTypes).
		if e.Len != nil {
			a.expr(e.Len)
		}
		a.typ(e.Elem)
	case *syntax.SliceType:
		a.typ(e.Elem) // []T (SGO-COMP-005)
	case *syntax.MapType:
		a.typ(e.Key) // map[K]V (SGO-COMP-006); types2 checks that K is a value type
		a.typ(e.Value)
	case *syntax.ChanType:
		a.chanElem(e.Elem)
	case *syntax.StructType:
		// Admitted only as the definition of a named type (typeDecl, SGO-COMP-002).
		a.deny(e.Pos(), "anonymous struct type", "SGO-COMP-001")
	case *syntax.InterfaceType:
		a.deny(e.Pos(), "interface type", "SGO-IFACE-001")
	case *syntax.ListExpr: // the type arguments of sgo.Call[Req, Resp], sgo.Request[Req, Resp] (D174)
		for _, x := range e.ElemList {
			a.typ(x)
		}
	case *syntax.IndexExpr:
		if sel, ok := e.X.(*syntax.SelectorExpr); ok && isSgo(sel) && (sel.Sel.Value == "Frozen" || sel.Sel.Value == "Result") {
			a.typ(e.Index) // sgo.Frozen[T] (SGO-COMP-009), sgo.Result[T] (D168); types2 checks T
			return
		}
		if sel, ok := e.X.(*syntax.SelectorExpr); ok && isSgo(sel) && sgoGeneric[sel.Sel.Value] {
			a.deny(e.Pos(), "sgo."+sel.Sel.Value+"[T] as a non-pointer type (admitted only as *sgo."+sel.Sel.Value+"[T])", "SGO-TYPE-005")
			return
		}
		a.deny(e.Pos(), "generic type instantiation", "SGO-GEN-001")
	default:
		a.deny(e.Pos(), "type expression", "SGO-TYPE-001")
	}
}

// sgoInstance reports whether e is sgo.M[T] for one of the members ms; it reports a denial and
// returns true (the instance is handled) when T is not an admitted channel element type.
func (a *admitter) sgoInstance(e *syntax.IndexExpr, ms ...string) bool {
	sel, ok := e.X.(*syntax.SelectorExpr)
	if !ok || !isSgo(sel) {
		return false
	}
	found := false
	for _, m := range ms {
		found = found || sel.Sel.Value == m
	}
	if !found {
		return false
	}
	if a.valueTypeSyntax(e.Index) {
		return true // types2 checks the type (sgoChanElemOK)
	}
	a.deny(e.Index.Pos(), "channel element type "+syntax.String(e.Index)+" (admitted: int, bool, string, error, and value types)", "SGO-PERMIT-002")
	return true
}

// chanElem checks a native channel element type: int, bool, string, error, or a channel of them
// (D36; SGO-CHAN-002).
func (a *admitter) chanElem(e syntax.Expr) {
	switch t := e.(type) {
	case *syntax.ChanType:
		a.chanElem(t.Elem)
		return
	case *syntax.ParenExpr:
		a.chanElem(t.X)
		return
	}
	if a.valueTypeSyntax(e) {
		return // a named or array type: types2 checks it is a value type (sgoChanElemOK)
	}
	a.deny(e.Pos(), "channel element type "+syntax.String(e)+" (admitted: int, bool, string, error, value types, and channels of them)", "SGO-CHAN-002")
}

// valueTypeSyntax reports whether e can denote an admitted element type: a type name (int, bool,
// string, error, or a named value type, SGO-COMP-002), a qualified name of another package's type,
// or an array type; it checks e as a type. The type checker decides whether the type is a value
// type.
func (a *admitter) valueTypeSyntax(e syntax.Expr) bool {
	switch t := syntax.Unparen(e).(type) {
	case *syntax.Name, *syntax.ArrayType, *syntax.SliceType, *syntax.MapType:
		a.typ(t)
		return true
	case *syntax.Operation:
		if t.Op == syntax.Mul && t.Y == nil {
			a.typ(t) // *T (SGO-COMP-007)
			return true
		}
	case *syntax.SelectorExpr:
		if isSgo(t) {
			return false // no type of package sgo is a value type
		}
		a.typ(t)
		return true
	case *syntax.IndexExpr:
		if sel, ok := t.X.(*syntax.SelectorExpr); ok && isSgo(sel) && sel.Sel.Value == "Frozen" {
			a.typ(t) // sgo.Frozen[T] is shareable (SGO-COMP-009)
			return true
		}
	}
	return false
}

func isSgo(sel *syntax.SelectorExpr) bool {
	x, ok := sel.X.(*syntax.Name)
	return ok && x.Value == "sgo"
}

// sgoSelector checks pkg.Member: members of package sgo must be admitted. Other selectors (user
// packages, method calls) are checked by the type checker.
func (a *admitter) sgoSelector(e *syntax.SelectorExpr) {
	if isSgo(e) {
		if !sgoMembers[e.Sel.Value] && !(TestMain && e.Sel.Value == "StartTest") {
			a.deny(e.X.Pos(), "sgo."+e.Sel.Value, "SGO-ERR-001")
		}
		return
	}
	a.expr(e.X)
}

func (a *admitter) name(n *syntax.Name) {
	if clause, ok := deniedNames[n.Value]; ok {
		a.deny(n.Pos(), "predeclared "+n.Value, clause)
	}
}

func (a *admitter) expr(e syntax.Expr) {
	switch e := e.(type) {
	case nil:
	case *syntax.CheckExpr:
		a.expr(e.X) // check c (SGO-ERR-004): where it may stand is a types2 rule (sgo_check.go)
	case *syntax.Name:
		a.name(e)
	case *syntax.BasicLit:
		a.basicLit(e)
	case *syntax.CompositeLit:
		// Literals of named struct types and of array types (SGO-COMP-002); types2 checks the type.
		if e.Type != nil {
			a.typ(e.Type)
		}
		for _, x := range e.ElemList {
			if kv, ok := x.(*syntax.KeyValueExpr); ok {
				if _, isName := kv.Key.(*syntax.Name); !isName {
					a.expr(kv.Key) // an array index; a field name is not an expression
				}
				a.expr(kv.Value)
				continue
			}
			a.expr(x)
		}
	case *syntax.KeyValueExpr:
		a.deny(e.Pos(), "key-value expression", "SGO-COMP-001")
	case *syntax.FuncLit:
		a.funcType(e.Type)
		a.stmt(e.Body)
	case *syntax.ParenExpr:
		a.expr(e.X)
	case *syntax.SelectorExpr:
		a.sgoSelector(e)
	case *syntax.IndexExpr:
		if a.sgoInstance(e, "NewChannel") {
			return
		}
		// Array indexing (SGO-COMP-003); types2 denies every other operand (sgoIndex).
		a.expr(e.X)
		a.expr(e.Index)
	case *syntax.SliceExpr:
		a.expr(e.X) // slicing (SGO-COMP-005)
		for _, x := range e.Index {
			a.expr(x)
		}
	case *syntax.AssertExpr:
		// Only the comma-ok form is admitted (stmt, D129); x.(T) would panic on a mismatch.
		a.deny(e.Pos(), "single-value type assertion "+syntax.String(e)+" (use v, ok := x.(T) or a type switch)", "SGO-IFACE-001")
	case *syntax.Operation:
		switch {
		case e.Y == nil && e.Op == syntax.And:
			a.expr(e.X) // &x (SGO-COMP-007)
		case e.Y == nil && e.Op == syntax.Recv:
			a.expr(e.X)
		case e.Y == nil && e.Op == syntax.Mul:
			a.typ(e)
		default:
			a.expr(e.X)
			a.expr(e.Y)
		}
	case *syntax.CallExpr:
		// Conversions to int, string, bool, and error are checked by types2: only from a named type
		// with that underlying type (SGO-TYPE-002, SGO-UTYPE-002; sgoConversion).
		if n, ok := e.Fun.(*syntax.Name); ok && n.Value == "make" && len(e.ArgList) > 0 {
			if ct, ok := e.ArgList[0].(*syntax.ChanType); ok {
				// make(chan T) and make(chan T, n) are the only constructors (SGO-CHAN-002).
				a.typ(ct)
				for _, x := range e.ArgList[1:] {
					a.expr(x)
				}
				return
			}
		}
		if n, ok := e.Fun.(*syntax.Name); e.HasDots && !(ok && n.Value == "append") {
			a.deny(e.Pos(), "variadic call", "SGO-TYPE-003") // append(s, t...) is admitted (SGO-COMP-005)
			return
		}
		a.expr(e.Fun)
		for _, x := range e.ArgList {
			a.expr(x)
		}
	case *syntax.ListExpr:
		for _, x := range e.ElemList {
			a.expr(x)
		}
	default:
		a.typ(e)
	}
}

// commaOK checks the operands of a comma-ok type assertion v, ok := x.(T) (SGO-IFACE-004).
func (a *admitter) commaOK(x *syntax.AssertExpr) {
	a.expr(x.X)
	a.typ(x.Type)
}

func (a *admitter) basicLit(l *syntax.BasicLit) {
	switch l.Kind {
	case syntax.FloatLit, syntax.ImagLit:
		a.deny(l.Pos(), "floating-point or imaginary literal", "SGO-FLOAT-001")
	case syntax.RuneLit:
		// Admitted from spec 0.12.0 (SGO-LEX-004 v2, D119). The scanner has already refused
		// malformed literals and \u/\U escapes naming a surrogate or a value above 0x10FFFF.
		a.escapes(l, "ntr\\'xuU")
	case syntax.IntLit:
		if legacyOctal.MatchString(l.Value) {
			a.report(l.Pos(), "SGO_E_SYNTAX", "legacy octal literal "+l.Value+"; write 0o"+strings.TrimLeft(l.Value, "0")+" (SGO-LEX-004)")
		}
	case syntax.StringLit:
		if strings.HasPrefix(l.Value, "`") {
			return
		}
		a.escapes(l, "ntr\\\"xuU")
	}
}

// escapes denies every escape of an interpreted string or rune literal whose letter is not in
// allowed (SGO-LEX-004 v2, D119): \a \b \f \v and octal escapes stay denied. The scanner has
// already checked each escape's form, so the digit counts below are exact.
func (a *admitter) escapes(l *syntax.BasicLit, allowed string) {
	v := l.Value
	for i := 1; i < len(v)-1; i++ {
		if v[i] != '\\' {
			continue
		}
		c := v[i+1]
		if !strings.ContainsRune(allowed, rune(c)) {
			a.deny(a.posAt(l.Pos(), a.offset(l.Pos())+i), "escape \\"+string(c), "SGO-LEX-004")
			return
		}
		switch c {
		case 'x':
			i += 3
		case 'u':
			i += 5
		case 'U':
			i += 9
		default:
			i++
		}
	}
}
