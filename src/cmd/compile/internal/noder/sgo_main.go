// sgoMainWrapper synthesizes the Go entry point of an S-Go program (SGO-PROC-001, SGO-PROC-002).
// The user's func main(root *sgo.Context) error is linked as main·sgo (isSgoMain); the runtime
// still enters main.main, which is
//
//	func main() {
//		c := sgoEnterMain()               // the root task (creation ID 0) and its context
//		err := main·sgo((*sgo.Context)(c))
//		sgoExitMain(err)                 // nil: exit status 0; else MainError, status 1
//	}
//
// A failure that unwinds out of main·sgo never returns here: the runtime completes the open
// nurseries (SGO-DEF-005) and ends the process with the diagnostic record (sgo_main.go).
func sgoMainWrapper(target *ir.Package) {
	var user *ir.Func
	for _, fn := range target.Funcs {
		if fn.Sym().Pkg == types.LocalPkg && fn.Sym().Name == sgoMainName {
			user = fn
		}
	}
	if user == nil {
		return // reported by the type checker (SGO_E_MAIN_SIGNATURE)
	}
	params := user.Type().Params()
	if len(params) != 1 || !params[0].Type.IsPtr() || user.Type().NumResults() != 1 {
		base.FatalfAt(user.Pos(), "S-Go: unexpected main signature %v", user.Type())
	}

	pos := base.AutogeneratedPos
	base.Pos = pos
	fn := ir.NewFunc(pos, pos, typecheck.Lookup("main"), types.NewSignature(nil, nil, nil))
	fn.SetInlinabilityChecked(true)
	typecheck.DeclFunc(fn)

	enter := typecheck.Call(pos, typecheck.LookupRuntime("sgoEnterMain"), nil, false)
	root := typecheck.ConvNop(enter, params[0].Type)
	call := typecheck.Call(pos, user.Nname, []ir.Node{root}, false)
	exit := typecheck.Call(pos, typecheck.LookupRuntime("sgoExitMain"), []ir.Node{call}, false)
	fn.Body = []ir.Node{typecheck.Stmt(exit)}

	typecheck.FinishFuncBody()
}
